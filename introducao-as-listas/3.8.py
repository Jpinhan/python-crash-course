viagem = ["Cataratas do Iguaçu", "Fernando de Noronha", "Transatlantico", "Itália", "Roma"]
print(viagem)
# Utilize sorted() para exibir sua lista em ordem alfabética, sem modificar a lista propriamente dita.
print(sorted(viagem))
print(viagem)
viagem.reverse()
print(viagem)
viagem.reverse()
print(viagem)
viagem.sort()
print(viagem)
viagem.sort(reverse = True)
print(viagem)